"""Validate Overture snapshots; catalog imports use cumulative source budgets."""

import argparse
import json
import math
import re
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from collect_overture import CITIES, RELEASE
from sqlalchemy import select
from sqlalchemy.orm import sessionmaker

from app import ingestion
from app.bulk_collect import check_readiness, load_settings, safe_error
from app.db import make_engine
from app.http import aware, utcnow
from app.models import CityAlias, DataSource, ImportPermit, Place, PlaceExternalId
from app.overture import adapt_record, import_snapshot, separate_duplicates

SOURCE = "Overture Maps Places — see source attribution"
LICENSE = "https://docs.overturemaps.org/attribution/"
FIELDS = {
    "external_id",
    "kind",
    "name",
    "source_url",
    "observed_at",
    "coordinates",
    "evidence",
    "address",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", type=Path, required=True)
    parser.add_argument("--env-file", type=Path, required=True)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--catalog", type=Path, help="City catalog generated by batch collector")
    parser.add_argument(
        "--max-records", type=int, default=100000, help="Cumulative source budget, not per run"
    )
    args = parser.parse_args()
    if not 1 <= args.max_records <= 100000:
        parser.error("max-records must be 1..100000")
    configs = CITIES
    if args.catalog:
        catalog = json.loads(args.catalog.read_text())
        if catalog.get("release") != RELEASE:
            raise ValueError("CATALOG_RELEASE_MISMATCH")
        configs = catalog["cities"]
        for qid, cfg in configs.items():
            bounds = cfg.get("bounds", [])
            names = cfg.get("names", [])
            if (
                not re.fullmatch(r"Q[1-9][0-9]*", qid)
                or cfg.get("qid") != qid
                or not names
                or any(not isinstance(n, str) or not 0 < len(n) <= 100 for n in names)
                or len(bounds) != 4
                or any(not isinstance(v, (int, float)) or not math.isfinite(v) for v in bounds)
                or not (73 <= bounds[0] < bounds[2] <= 136 and 17 <= bounds[1] < bounds[3] <= 55)
            ):
                raise ValueError("INVALID_CITY_CONFIG")
    if args.snapshot.stat().st_size > 20_000_000:
        raise ValueError("SNAPSHOT_TOO_LARGE")
    snapshot = json.loads(args.snapshot.read_text())
    if (
        snapshot["release"] != RELEASE
        or snapshot["city"] not in configs.values()
        or len(snapshot["records"]) > 2000
    ):
        raise ValueError("SNAPSHOT_CONFIG_UNVERIFIED")
    cfg = snapshot["city"]
    observed = datetime.fromtimestamp(args.snapshot.stat().st_mtime, timezone.utc).isoformat()
    engine = make_engine(load_settings(args.env_file))
    try:
        check_readiness(engine)
        sessions = sessionmaker(engine, expire_on_commit=False)
        with sessions() as db:
            city = db.scalar(
                select(CityAlias.city_id).where(
                    CityAlias.namespace == "wikidata",
                    CityAlias.external_id == cfg["qid"],
                )
            )
            if not city and not args.catalog:
                raise ValueError("CITY_NOT_REGISTERED")
            existing = [
                {
                    "name": p.name,
                    "kind": p.kind,
                    "coordinates": {
                        "longitude": p.longitude,
                        "latitude": p.latitude,
                        "crs": p.coordinate_system,
                    }
                    if p.latitude is not None
                    else None,
                }
                for p in db.scalars(select(Place).where(Place.city_id == city))
            ]
            source = db.scalar(select(DataSource.id).where(DataSource.name == SOURCE))
            known = (
                set(
                    db.scalars(
                        select(PlaceExternalId.external_id).where(
                            PlaceExternalId.source_id == source
                        )
                    )
                )
                if source
                else set()
            )
            if args.apply and source:
                ingestion.policy_for(db, source)
                permit_row = db.scalar(select(ImportPermit).where(ImportPermit.source_id == source))
                if permit_row and aware(permit_row.expires_at) <= utcnow():
                    raise ValueError("IMPORT_PERMIT_EXPIRED")
        records = []
        rejected = Counter()
        for row in snapshot["records"]:
            try:
                records.append(
                    adapt_record(
                        row,
                        city_names=cfg["names"],
                        bounds=cfg["bounds"],
                        release=RELEASE,
                        observed_at=observed,
                    )
                )
            except (ValueError, KeyError, TypeError) as error:
                rejected[safe_error(error)] += 1
        already_imported = sum(r["external_id"] in known for r in records)
        records = [r for r in records if r["external_id"] not in known]
        accepted, review = separate_duplicates(records, existing)
        selected = []
        for kind in ("hotel", "restaurant"):
            selected.extend(
                [r for r in accepted if r["kind"] == kind][: (2000 if args.catalog else 30)]
            )
        print(
            json.dumps(
                {
                    "accepted_before_dedup": len(records),
                    "already_imported": already_imported,
                    "held_for_duplicate_review": len(review),
                    "selected": dict(Counter(r["kind"] for r in selected)),
                    "rejected": dict(rejected),
                },
                ensure_ascii=False,
            )
        )
        if not args.apply or not selected:
            return
        if source is None:
            source = ingestion.register_policy(
                sessions,
                SOURCE,
                LICENSE,
                "Overture Places 2026-10-21.0; per-record CC0/CDLA-Permissive-2.0/Apache-2.0 evidence retained; no images or ratings; official attribution reviewed",
                FIELDS,
                computation_allowed=True,
            )
        if city is None:
            city = ingestion.register_city(sessions, "wikidata", cfg["qid"], cfg["names"][-1])
        with sessions() as db:
            ingestion.policy_for(db, source)
            permit = db.scalar(select(ImportPermit.id).where(ImportPermit.source_id == source))
            cities = list(
                db.scalars(
                    select(CityAlias.city_id).where(
                        CityAlias.namespace == "wikidata",
                        CityAlias.external_id.in_([v["qid"] for v in configs.values()]),
                    )
                )
            )
        if permit is None:
            ingestion.grant_permit(
                sessions,
                source,
                cities,
                args.max_records if args.catalog else 1000,
                "Operator requested bounded Overture import from explicit city catalog",
            )
        elif args.catalog:
            with sessions.begin() as db:
                ingestion.policy_for(db, source, True)
                row = db.scalar(
                    select(ImportPermit).where(ImportPermit.source_id == source).with_for_update()
                )
                if aware(row.expires_at) <= utcnow():
                    raise ValueError("IMPORT_PERMIT_EXPIRED")
                if args.max_records < row.used_records:
                    raise ValueError("BUDGET_ALREADY_CONSUMED")
                row.city_ids = sorted(set(row.city_ids) | {city})
                row.max_records = args.max_records
                row.reference = "Operator requested catalog import; counters and expiry retained"
        print(
            json.dumps(
                {
                    "batches": import_snapshot(
                        sessions,
                        source,
                        city,
                        selected,
                        "Validated source license, locality, WGS84 point; nearby duplicates withheld; operating status may be unknown",
                    )
                },
                ensure_ascii=False,
            )
        )
    finally:
        engine.dispose()


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(json.dumps({"error": safe_error(error)}))
        raise SystemExit(1) from None
