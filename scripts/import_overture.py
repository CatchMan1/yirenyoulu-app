"""Validate Overture snapshots; catalog imports use cumulative source budgets."""

import argparse
import json
import math
import re
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from collect_overture import CITIES, RELEASE, validate_release
from sqlalchemy import select
from sqlalchemy.orm import sessionmaker

from app import ingestion
from app.bulk_collect import check_readiness, load_settings, safe_error
from app.db import make_engine
from app.http import aware, utcnow
from app.models import (
    CityAlias,
    DataSource,
    ImportPermit,
    Place,
    PlaceExternalId,
    PlaceFieldProvenance,
)
from app.overture import adapt_record, import_snapshot, release_key, separate_duplicates

SOURCE = "Overture Maps Places — see source attribution"
LICENSE = "https://docs.overturemaps.org/attribution/"
FIELDS = {
    "external_id",
    "kind",
    "name",
    "source_url",
    "observed_at",
    "coordinates",
    "evidence",
    "address",
    "status",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", type=Path, required=True)
    parser.add_argument("--env-file", type=Path, required=True)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument(
        "--refresh-existing",
        action="store_true",
        help="Update known source IDs; preserve snapshots and reject older releases",
    )
    parser.add_argument("--catalog", type=Path, help="City catalog generated by batch collector")
    parser.add_argument(
        "--max-records",
        type=int,
        help="Explicit cumulative budget; omit to retain an existing permit",
    )
    args = parser.parse_args()
    if args.max_records is not None and not 1 <= args.max_records <= 100000:
        parser.error("max-records must be 1..100000")
    if args.snapshot.stat().st_size > 20_000_000:
        raise ValueError("SNAPSHOT_TOO_LARGE")
    snapshot = json.loads(args.snapshot.read_text())
    release = validate_release(snapshot["release"])
    # Knowledge belongs to the release, never the copy/download time of a local file.
    day, _sequence = release.split(".")
    observed_at = datetime.fromisoformat(day).replace(tzinfo=timezone.utc)
    if observed_at > utcnow():
        raise ValueError("FUTURE_RELEASE")
    observed = observed_at.isoformat()
    configs = CITIES
    if args.catalog:
        catalog = json.loads(args.catalog.read_text())
        if catalog.get("release") != release:
            raise ValueError("CATALOG_RELEASE_MISMATCH")
        configs = catalog["cities"]
        for qid, cfg in configs.items():
            bounds = cfg.get("bounds", [])
            names = cfg.get("names", [])
            if (
                not re.fullmatch(r"Q[1-9][0-9]*", qid)
                or cfg.get("qid") != qid
                or not names
                or any(not isinstance(n, str) or not 0 < len(n) <= 100 for n in names)
                or len(bounds) != 4
                or any(not isinstance(v, (int, float)) or not math.isfinite(v) for v in bounds)
                or not (73 <= bounds[0] < bounds[2] <= 136 and 17 <= bounds[1] < bounds[3] <= 55)
            ):
                raise ValueError("INVALID_CITY_CONFIG")
    if (
        (not args.catalog and release != RELEASE)
        or snapshot["city"] not in configs.values()
        or len(snapshot["records"]) > 2000
    ):
        raise ValueError("SNAPSHOT_CONFIG_UNVERIFIED")
    cfg = snapshot["city"]
    engine = make_engine(load_settings(args.env_file))
    try:
        check_readiness(engine)
        sessions = sessionmaker(engine, expire_on_commit=False)
        with sessions() as db:
            city = db.scalar(
                select(CityAlias.city_id).where(
                    CityAlias.namespace == "wikidata",
                    CityAlias.external_id == cfg["qid"],
                )
            )
            if not city and not args.catalog:
                raise ValueError("CITY_NOT_REGISTERED")
            existing = [
                {
                    "name": p.name,
                    "kind": p.kind,
                    "coordinates": {
                        "longitude": p.longitude,
                        "latitude": p.latitude,
                        "crs": p.coordinate_system,
                    }
                    if p.latitude is not None
                    else None,
                }
                for p in db.scalars(select(Place).where(Place.city_id == city))
            ]
            source = db.scalar(select(DataSource.id).where(DataSource.name == SOURCE))
            # Provenance provides release ordering even for legacy imports whose fetched_at was mtime.
            previous = {}
            snapshot_ids = [
                r.get("id")
                for r in snapshot["records"]
                if isinstance(r, dict) and isinstance(r.get("id"), str)
            ]
            if source:
                for ext, place, provenance in db.execute(
                    select(PlaceExternalId, Place, PlaceFieldProvenance)
                    .join(Place, Place.id == PlaceExternalId.place_id)
                    .outerjoin(
                        PlaceFieldProvenance,
                        (PlaceFieldProvenance.place_id == Place.id)
                        & (PlaceFieldProvenance.field == "name"),
                    )
                    .where(
                        PlaceExternalId.source_id == source,
                        PlaceExternalId.external_id.in_(snapshot_ids),
                    )
                ):
                    previous[ext.external_id] = (
                        place.city_id,
                        place.kind,
                        ext.fetched_at,
                        (provenance.context or {}).get("evidence", {}) if provenance else {},
                    )
            known = set(previous)
            if args.apply and source:
                policy = ingestion.policy_for(db, source)
                permitted_fields = set(policy.allowed_fields)
                permit_row = db.scalar(select(ImportPermit).where(ImportPermit.source_id == source))
                if permit_row and aware(permit_row.expires_at) <= utcnow():
                    raise ValueError("IMPORT_PERMIT_EXPIRED")
        records = []
        rejected = Counter()
        for row in snapshot["records"]:
            try:
                records.append(
                    adapt_record(
                        row,
                        city_names=cfg["names"],
                        bounds=cfg["bounds"],
                        release=release,
                        observed_at=observed,
                        allow_closed=args.refresh_existing and row.get("id") in known,
                    )
                )
            except (ValueError, KeyError, TypeError) as error:
                rejected[safe_error(error)] += 1
        already_imported = sum(r["external_id"] in known for r in records)
        fresh, updates = [], []
        stale = 0
        for record in records:
            identity = previous.get(record["external_id"])
            if identity:
                if not args.refresh_existing:
                    continue
                old_city, old_kind, fetched, evidence = identity
                if old_city != city or old_kind != record["kind"]:
                    raise ValueError("IDENTITY_CONFLICT")
                old_release = evidence.get("release")
                if old_release:
                    validate_release(old_release)
                    if release_key(release) <= release_key(old_release):
                        stale += 1
                        continue
                elif fetched and aware(fetched) >= observed_at:
                    stale += 1
                    continue
                updates.append(record)
            elif record.get("status") != "inactive":
                fresh.append(record)
        accepted, review = separate_duplicates(fresh, existing)
        accepted.extend(updates)
        selected = []
        for kind in ("hotel", "restaurant"):
            selected.extend(
                [r for r in accepted if r["kind"] == kind][: (2000 if args.catalog else 30)]
            )
        print(
            json.dumps(
                {
                    "accepted_before_dedup": len(records),
                    "already_imported": already_imported,
                    "refresh_existing": args.refresh_existing,
                    "release": release,
                    "stale_or_same_release": stale,
                    "updates_selected": sum(r["external_id"] in known for r in selected),
                    "closures_selected": sum(r.get("status") == "inactive" for r in selected),
                    "held_for_duplicate_review": len(review),
                    "selected": dict(Counter(r["kind"] for r in selected)),
                    "rejected": dict(rejected),
                },
                ensure_ascii=False,
            )
        )
        if not args.apply or not selected:
            return
        if source is not None and any(not set(r) <= permitted_fields for r in selected):
            raise ValueError("UNLICENSED_FIELD")
        if source is None:
            source = ingestion.register_policy(
                sessions,
                SOURCE,
                LICENSE,
                f"Overture Places {release}; per-record CC0/CDLA-Permissive-2.0/Apache-2.0 evidence retained; no images or ratings; official attribution reviewed",
                FIELDS,
                computation_allowed=True,
            )
        if city is None:
            city = ingestion.register_city(sessions, "wikidata", cfg["qid"], cfg["names"][-1])
        with sessions() as db:
            ingestion.policy_for(db, source)
            permit = db.scalar(select(ImportPermit.id).where(ImportPermit.source_id == source))
            cities = list(
                db.scalars(
                    select(CityAlias.city_id).where(
                        CityAlias.namespace == "wikidata",
                        CityAlias.external_id.in_([v["qid"] for v in configs.values()]),
                    )
                )
            )
        if permit is None:
            ingestion.grant_permit(
                sessions,
                source,
                cities,
                (args.max_records or 100000) if args.catalog else (args.max_records or 1000),
                "Operator requested bounded Overture import from explicit city catalog",
            )
        elif args.catalog:
            with sessions.begin() as db:
                ingestion.policy_for(db, source, True)
                row = db.scalar(
                    select(ImportPermit).where(ImportPermit.source_id == source).with_for_update()
                )
                if aware(row.expires_at) <= utcnow():
                    raise ValueError("IMPORT_PERMIT_EXPIRED")
                if args.max_records is not None and args.max_records < row.used_records:
                    raise ValueError("BUDGET_ALREADY_CONSUMED")
                row.city_ids = sorted(set(row.city_ids) | {city})
                if args.max_records is not None:
                    row.max_records = args.max_records
                row.reference = "Operator requested catalog import; counters and expiry retained"
        print(
            json.dumps(
                {
                    "batches": import_snapshot(
                        sessions,
                        source,
                        city,
                        selected,
                        "Validated source license, locality, WGS84 point; nearby duplicates withheld; operating status may be unknown",
                    )
                },
                ensure_ascii=False,
            )
        )
    finally:
        engine.dispose()


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(json.dumps({"error": safe_error(error)}))
        raise SystemExit(1) from None
